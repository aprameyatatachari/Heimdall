def test_expected_shortfall_is_at_least_var_on_the_golden_data(golden):
    var = calc.historical_var(
        golden["portfolio_returns"], confidence=0.95, portfolio_value=100_000.0
    )
    shortfall = calc.expected_shortfall(
        golden["portfolio_returns"], confidence=0.95, portfolio_value=100_000.0
    )

    assert shortfall >= var


def test_parametric_var_matches_the_independent_calculation(golden):
    from scipy import stats

    returns = golden["portfolio_returns"]
    mean = statistics.fmean(returns)
    deviation = statistics.stdev(returns)
    expected = max(-(mean + float(stats.norm.ppf(0.05)) * deviation) * 100_000.0, 0.0)

    assert calc.parametric_var(
        returns, confidence=0.95, portfolio_value=100_000.0
    ) == pytest.approx(expected, rel=1e-8)


# --- Covariance and attribution ----------------------------------------------


def test_covariance_matches_the_independent_calculation(golden):
    first = golden["returns"]["GLDA"]
    second = golden["returns"]["GLDB"]
    matrix = list(zip(first, second, strict=True))

    covariance = calc.covariance_matrix(matrix, annualize=False)

    assert covariance[0][0] == pytest.approx(
        independent_covariance(first, first), rel=RELATIVE_TOLERANCE
    )
    assert covariance[0][1] == pytest.approx(
        independent_covariance(first, second), rel=RELATIVE_TOLERANCE
    )
    assert covariance[1][1] == pytest.approx(
        independent_covariance(second, second), rel=RELATIVE_TOLERANCE
    )


def test_correlation_matches_the_independent_calculation(golden):
    first = golden["returns"]["GLDA"]
    second = golden["returns"]["GLDB"]
    matrix = list(zip(first, second, strict=True))

    correlation = calc.correlation_matrix(matrix)

    assert correlation[0][1] == pytest.approx(
        independent_correlation(first, second), rel=RELATIVE_TOLERANCE
    )


def test_portfolio_volatility_from_covariance_matches_the_return_series(golden):
    """Two routes to the same number: the return series, and w' * C * w."""
    weights = [golden["weights"][symbol] for symbol in golden["symbols"]]
    matrix = list(zip(*[golden["returns"][symbol] for symbol in golden["symbols"]], strict=True))

    from_series = calc.volatility(golden["portfolio_returns"], annualize=False)
    from_covariance = calc.portfolio_volatility_from_covariance(
        weights,
        calc.covariance_matrix(matrix, annualize=False),
    )

    assert from_covariance == pytest.approx(from_series, rel=1e-9)


def test_risk_contributions_reconcile_on_the_golden_data(golden):
    weights = [golden["weights"][symbol] for symbol in golden["symbols"]]
    matrix = list(zip(*[golden["returns"][symbol] for symbol in golden["symbols"]], strict=True))
    covariance = calc.covariance_matrix(matrix)

    total = calc.portfolio_volatility_from_covariance(weights, covariance)
    contributions = calc.risk_contributions(weights, covariance)

    assert sum(item.component for item in contributions) == pytest.approx(total, rel=1e-12)
    assert sum(item.share for item in contributions) == pytest.approx(1.0, rel=1e-12)


def test_the_negatively_correlated_asset_reduces_total_risk(golden):
    """GLDB moves against GLDA, so its component contribution is negative.

    A diversifying holding genuinely lowers portfolio volatility; the attribution
    must show that rather than clamping every contribution to be positive.
    """
    weights = [golden["weights"][symbol] for symbol in golden["symbols"]]
    matrix = list(zip(*[golden["returns"][symbol] for symbol in golden["symbols"]], strict=True))
    contributions = calc.risk_contributions(weights, calc.covariance_matrix(matrix))

    assert contributions[0].share > contributions[1].share


# --- Documented reference values ----------------------------------------------


def test_documented_reference_values(golden):
    """Values quoted in docs/financial-methodology.md.

    If a calculation changes, this test fails and the documentation must be
    updated in the same commit.
    """
    returns = golden["portfolio_returns"]
    path = calc.value_history(returns, starting_value=100_000.0)

    assert round(golden["weights"]["GLDA"], 6) == 0.713699
    assert round(golden["weights"]["GLDB"], 6) == 0.286301

    assert round(calc.cumulative_return(returns), 6) == 0.059549
    assert round(calc.annualized_return(returns), 6) == 0.280254
    assert round(calc.volatility(returns, annualize=False), 6) == 0.013319
    assert round(calc.volatility(returns), 6) == 0.211435
    assert round(calc.sharpe_ratio(returns), 6) == 1.272574
    assert round(calc.sharpe_ratio(returns, annual_risk_free_rate=0.045), 6) == 1.064375
    assert round(calc.max_drawdown(path).drawdown, 6) == -0.025398

    historical = calc.historical_var(returns, confidence=0.95, portfolio_value=100_000.0)
    parametric = calc.parametric_var(returns, confidence=0.95, portfolio_value=100_000.0)
    shortfall = calc.expected_shortfall(returns, confidence=0.95, portfolio_value=100_000.0)

    assert round(historical, 2) == 1555.21
    assert round(parametric, 2) == 2084.04
    assert round(shortfall, 2) == 1555.21
